"""GPU MAE boosting plus the validated parent ensemble, selection without holdout."""
import argparse, hashlib, json, os, pickle, sys
from pathlib import Path
sys.path.insert(0,str(Path.cwd()/'catboost_vendor'))
import numpy as np
import pandas as pd
import torch
from catboost import CatBoostRegressor
from scipy.optimize import minimize
from reconstruction import read_targets,rich_features,baseline,project
from catboost_models import quarter_features,cat_prediction,constrain_residual,learn_projection

def main():
    p=argparse.ArgumentParser();p.add_argument('--smoke',action='store_true');p.add_argument('--projection-refine',action='store_true');p.add_argument('--parent-dir',default='results/zone_search_gpu1');p.add_argument('--defer-refit',action='store_true');p.add_argument('--out',default='results/catboost_search_gpu1');a=p.parse_args()
    assert os.environ.get('CUDA_VISIBLE_DEVICES')=='1'
    assert torch.cuda.is_available()
    out=Path(a.out);out.mkdir(parents=True,exist_ok=True)
    parent_dir=Path(a.parent_dir)
    report0=json.loads((parent_dir/'metrics.json').read_text())
    assert report0.get('offline_inference_qa','').startswith('passed')
    dates,y=read_targets('train_prices_15min.csv');h=y.mean(-1);b=baseline(h)
    sha=hashlib.sha256(Path('train_prices_15min.csv').read_bytes()).hexdigest()
    assert sha==report0['source_sha256']
    # Trusted cache generated by this project's own trainer; dates were object strings.
    cache=np.load(parent_dir/'selection_predictions.npz',allow_pickle=True)
    assert np.array_equal(cache['dates'],dates) and np.array_equal(cache['truth'],y)
    parent_weights=np.array(report0['weights']);cp=cache['candidates']
    assert cp.shape[0]==len(parent_weights)
    parent_prediction=(cp.reshape(len(cp),-1,4,24,4)*parent_weights[:,None,:,None,None]).sum(0).reshape(-1,4)
    x=rich_features(dates,h,dates,y);xp=quarter_features(x)
    counts=report0.get('split_counts',dict(train=len(dates)-120,validation=60,test=60))
    train_days=counts['train'];validation_end=train_days+counts['validation']
    tr=train_days*96;va=validation_end*96
    truth=y.reshape(-1,4);base=b.reshape(-1,4);target=(truth-base)/20
    assert abs(np.abs(parent_prediction[tr:va]-truth[tr:va]).mean()-report0['validation']['mae'])<1e-9
    predictions=[parent_prediction,base];meta=[dict(name='parent_ensemble',config={}),dict(name='interpolation',config={})]
    fitted=[None,None]
    configs=[]
    for depth in [6,8]:
        for lr in [.03,.08]:
            for l2 in [3,30]:configs.append(dict(depth=depth,learning_rate=lr,l2_leaf_reg=l2,strategy='pooled',seed=17))
    configs.append(dict(depth=10,learning_rate=.03,l2_leaf_reg=30,strategy='pooled',seed=43))
    for depth in [6,8]:configs.append(dict(depth=depth,learning_rate=.05,l2_leaf_reg=30,strategy='quarter',seed=17))
    if a.projection_refine:
        prior=json.loads(Path('results/catboost_search_gpu1/metrics.json').read_text())
        assert prior.get('offline_inference_qa','').startswith('passed')
        cats=[(c,w) for c,w in zip(prior['candidates'],prior['weights']) if c['name'].startswith('cat_')]
        chosen=[c for c,w in cats if np.any(w)]
        chosen+=sorted([c for c,w in cats if c not in chosen],key=lambda c:c['validation_mae'])[:2]
        chosen=sorted(chosen,key=lambda c:c['validation_mae'])[:6]
        configs=[dict(c['config'],fixed_epochs=c['config']['epochs']) for c in chosen]
    if a.smoke:configs=[configs[0]]
    def params(cfg,iterations):
        return dict(iterations=iterations,depth=cfg['depth'],learning_rate=cfg['learning_rate'],
            l2_leaf_reg=cfg['l2_leaf_reg'],random_seed=cfg['seed'],loss_function='MAE',eval_metric='MAE',
            task_type='GPU',devices='0',gpu_ram_part=.5,thread_count=4,border_count=128,
            allow_writing_files=False,verbose=False)
    for i,cfg in enumerate(configs):
        fixed=a.projection_refine and not a.smoke
        iterations=3 if a.smoke else (cfg['fixed_epochs'][0] if fixed else 1800)
        if cfg['strategy']=='pooled':
            model=CatBoostRegressor(**params(cfg,iterations))
            if fixed:model.fit(xp[:tr*4],target[:tr].ravel())
            else:model.fit(xp[:tr*4],target[:tr].ravel(),eval_set=(xp[tr*4:va*4],target[tr:va].ravel()),
                early_stopping_rounds=100,use_best_model=True)
            epochs=[model.tree_count_]
        else:
            model=[];epochs=[]
            for q in range(4):
                mm=CatBoostRegressor(**params(cfg,cfg['fixed_epochs'][q] if fixed else iterations))
                if fixed:mm.fit(x[:tr],target[:tr,q])
                else:mm.fit(x[:tr],target[:tr,q],eval_set=(x[tr:va],target[tr:va,q]),early_stopping_rounds=100,use_best_model=True)
                model.append(mm);epochs.append(mm.tree_count_)
        raw=cat_prediction(model,cfg,x)
        config=dict(cfg,epochs=epochs)
        alternatives=[('cat_'+str(i),config)]
        if a.projection_refine:
            alpha,diag=learn_projection(raw*20,target*20,tr,va)
            alternatives.append(('cat_'+str(i)+'_projection',dict(config,projection_weights=alpha,projection_validation=diag)))
        for name,cc in alternatives:
            pp=base+20*constrain_residual(raw,cc)
            assert np.isfinite(pp).all()
            score=float(np.abs(pp[tr:va]-truth[tr:va]).mean())
            predictions.append(pp);fitted.append(model);meta.append(dict(name=name,config=cc,validation_mae=score))
            print(name,'validation',score,'trees',epochs,flush=True)
        (out/'validation_progress.json').write_text(json.dumps(meta,indent=2))
    preds=np.array(predictions);m=len(preds);err=preds[:,tr:va]-truth[None,tr:va]
    init=np.zeros(m);init[np.argmin(np.abs(err).mean((1,2)))]=1
    res=minimize(lambda w:np.abs(np.einsum('m,mnq->nq',w,err)).mean(),init,method='SLSQP',
        bounds=[(0,1)]*m,constraints={'type':'eq','fun':lambda w:w.sum()-1},options={'maxiter':300,'ftol':1e-8})
    ww=res.x if res.success else init;ww[ww<.005]=0;ww/=ww.sum()
    global_weights=ww.copy();zonal=[]
    for z in range(4):
        e=err.reshape(m,-1,4,24,4)[:,:,z].reshape(m,-1)
        rz=minimize(lambda w:np.abs(w@e).mean()+.05*np.sum((w-global_weights)**2),global_weights,
            method='SLSQP',bounds=[(0,1)]*m,constraints={'type':'eq','fun':lambda w:w.sum()-1},options={'maxiter':300,'ftol':1e-8})
        w=rz.x if rz.success else global_weights.copy();w[w<.005]=0;w/=w.sum();zonal.append(w)
    weights=np.array(zonal).T
    pred=(preds.reshape(m,-1,4,24,4)*weights[:,None,:,None,None]).sum(0).reshape(-1,4)
    def score(pp,sl):
        e=np.abs(pp[sl]-truth[sl]).reshape(-1,4,24,4)
        return dict(mae=float(e.mean()),mae_by_zone=e.mean((0,2,3)).tolist())
    report=dict(source_sha256=sha,split=report0['split'],candidates=meta,weights=weights.tolist(),
        validation=score(pred,slice(tr,va)),holdout=score(pred,slice(va,None)),
        holdout_baseline=score(base,slice(va,None)),max_hourly_mean_error=float(np.abs(pred.mean(-1)-h.ravel()).max()),
        feature_mode='rich',parent=parent_dir.name,smoke=a.smoke,split_counts=counts,calendar_split=report0.get('calendar_split',False),
        device=torch.cuda.get_device_name(0),catboost_version='1.2.8',projection_refine=a.projection_refine)
    assert report['max_hourly_mean_error']<1e-4
    if report['calendar_split']:report['test']=report['holdout'];report['test_baseline']=report['holdout_baseline']
    (out/'metrics.json').write_text(json.dumps(report,indent=2))
    np.savez_compressed(out/('test_predictions.npz' if report['calendar_split'] else 'heldout_predictions.npz'),dates=dates[validation_end:].astype('U10'),observed=y[validation_end:],predicted=pred[va:].reshape(-1,4,24,4),baseline=b[validation_end:])
    np.savez_compressed(out/'selection_predictions.npz',dates=dates.astype('U10'),truth=y,baseline=b,candidates=preds)
    with (parent_dir/'model.pkl').open('rb') as f:parent=pickle.load(f)
    bundle=dict(mu=parent['mu'],sd=parent['sd'],feature_mode='rich',feature_count=x.shape[1],source_sha256=sha,models=[])
    artifact_cache={}
    for item_index,(item,w) in enumerate(zip(meta,weights)):
        if not np.any(w):continue
        name=item['name'];cfg=item['config'];artifact=None
        print('Refit',name,'weights',w,flush=True)
        if name=='parent_ensemble':artifact=parent
        elif name.startswith('cat_'):
            if a.defer_refit:
                artifact=fitted[item_index]
                bundle['models'].append(dict(name=name,weight=w.tolist(),config=cfg,artifact=artifact))
                continue
            key=json.dumps({k:v for k,v in cfg.items() if not k.startswith('projection_')},sort_keys=True)
            if key in artifact_cache:artifact=artifact_cache[key]
            else:
                if cfg['strategy']=='pooled':
                    artifact=CatBoostRegressor(**params(cfg,cfg['epochs'][0]));artifact.fit(xp,target.ravel())
                else:
                    artifact=[]
                    for q in range(4):
                        mm=CatBoostRegressor(**params(cfg,cfg['epochs'][q]));mm.fit(x,target[:,q]);artifact.append(mm)
                artifact_cache[key]=artifact
        bundle['models'].append(dict(name=name,weight=w.tolist(),config=cfg,artifact=artifact))
    with (out/'model.pkl').open('wb') as f:pickle.dump(bundle,f)
    report['model_fit_days']=train_days if a.defer_refit else len(dates)
    report['final_refit_deferred']=a.defer_refit
    from predict import predict
    # Match the parent's official-format QA inputs; separately check exact exported values.
    predict(out/'model.pkl',parent_dir/'qa_hourly.csv',parent_dir/'qa_history.csv',out/'qa_predictions.csv')
    got=pd.read_csv(out/'qa_predictions.csv');keys=['delivery_date','market_id','hour_index']
    assert len(got)==384 and not got.duplicated(keys+['quarter_index']).any()
    assert np.isfinite(got.predicted_price_eur_mwh).all()
    agg=got.groupby(keys).predicted_price_eur_mwh.agg(['mean','count']).join(pd.read_csv(parent_dir/'qa_hourly.csv').set_index(keys))
    assert (agg['count']==4).all() and (agg['mean']-agg.hourly_price_eur_mwh).abs().max()<1e-4
    report['offline_inference_qa']='passed; 384 unique finite predictions and hourly means within tolerance'
    (out/'metrics.json').write_text(json.dumps(report,indent=2))
    print('DONE validation',report['validation'],'holdout',report['holdout'],flush=True)

if __name__=='__main__':main()
